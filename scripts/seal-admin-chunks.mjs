/**
 * Move the Writing Studio chunk out of the public Vite output and into a
 * server module. The public site must not ship that admin tool's copy.
 */
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const publicDir = path.join(root, "dist", "public");
const adminDir = path.join(publicDir, "assets", "admin");
const outFile = path.join(root, "server", "generated", "adminChunks.ts");

const chunks = {};

if (fs.existsSync(adminDir)) {
  for (const file of fs.readdirSync(adminDir)) {
    if (!file.endsWith(".js") && !file.endsWith(".css")) continue;
    const full = path.join(adminDir, file);
    chunks[file] = fs.readFileSync(full);
    fs.unlinkSync(full);
  }
  fs.rmSync(adminDir, { recursive: true, force: true });
}

if (Object.keys(chunks).length === 0) {
  console.error("[seal-admin-chunks] No Writing Studio chunk was emitted under dist/public/assets/admin.");
  console.error("[seal-admin-chunks] Refusing to leave that admin tool in the public build.");
  process.exit(1);
}

fs.mkdirSync(path.dirname(outFile), { recursive: true });

const body = Object.entries(chunks)
  .map(([name, bytes]) => `  ${JSON.stringify(name)}: ${JSON.stringify(bytes.toString("utf8"))}`)
  .join(",\n");

fs.writeFileSync(
  outFile,
  `// Generated by scripts/seal-admin-chunks.mjs. Do not commit the sealed contents.\n` +
    `export const adminChunks: Record<string, string> = {\n${body},\n};\n`,
);

console.log(`[seal-admin-chunks] Sealed ${Object.keys(chunks).length} file(s): ${Object.keys(chunks).join(", ")}`);

const forbidden = [
  "Hudson Dynasty AI Workflow System",
  "Anti-AI Pass",
  "Powered by AI",
  "Yung-Lung",
  "AI Trend Newsletter",
  "ai-assisted-romance-writing-workflow",
  "cutting-edge AI",
  "ElevenLabs AI",
];

function walk(dir) {
  const hits = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) hits.push(...walk(full));
    else if (/\.(js|css|html|txt|xml|json)$/.test(entry.name)) hits.push(full);
  }
  return hits;
}

const leaks = [];
for (const file of walk(publicDir)) {
  const text = fs.readFileSync(file, "utf8");
  for (const phrase of forbidden) {
    if (text.includes(phrase)) leaks.push(`${path.relative(root, file)}: ${phrase}`);
  }
}

if (leaks.length > 0) {
  console.error("[seal-admin-chunks] Public build still contains retired copy:");
  for (const leak of leaks) console.error(`  ${leak}`);
  process.exit(1);
}
